-- IFR curtain: an opaque bubble around the pilot's head, just beyond the canopy.
-- Everything inside the cockpit (panel, HUD, canopy frame) is closer than the bubble, so with
-- depth testing it is drawn in front of it, and only the outside world is hidden.
--
-- The bubble is a superellipsoid (a box with rounded edges and corners) that touches six
-- walls set per aircraft. It is made of flat facets; each facet is moved to its place and
-- turned to follow the surface by two nested pivots (yaw, then pitch).
--
-- Frame (measured in the A-10C): x right, y up, z forward. init_rot = {roll about z, yaw about
-- y, pitch about x}, in degrees, positive angles turning as the usual right-handed rotations
-- (roll: +y towards -x; yaw and pitch the same way: all three checked in flight on the A-10C).
dofile(LockOn_Options.common_script_path.."elements_defs.lua")

SetScale(METERS)

-- The shape of the bubble for each aircraft is in shapes.lua.

-- Size in meters of the facets, measured on the box before it is rounded, for a bubble
-- the size of the A-10C's; it grows with larger bubbles to keep the number of facets down.
local BASE_STEP = 0.25

-- Texture: one image covers the whole bubble, seen from any side, so it never has to
-- repeat (its size in meters is set below from the bubble's size; the image is drawn for
-- 3 m, the A-10C's, see tools/make_curtain_texture.py). Each facet takes its texture seen
-- from the side of the box it faces most (above, beside, in front), so the cloth is
-- stretched at most 1.4 times, on the 45-degree lines of the rounded edges.

-- Flip to -1 if the facets come out turned the wrong way (bubble broken into shards).
local YAW_SIGN = 1
local PITCH_SIGN = 1

-- DEBUG: chequerboard colours instead of the texture, to see the facets.
local DEBUG_COLOURS = false
local DEBUG_FACE_COLOURS = {{255, 140, 0, 255}, {0, 90, 255, 255}}

-- Curtain texture: crumpled canvas, seamless, generated by tools/make_curtain_texture.py.
local CURTAIN_TEXTURE = LockOn_Options.common_script_path.."IFR_CURTAIN/curtain.tga"
-- Multiplies the texture: DCS renders it much brighter than its raw pixels.
local CURTAIN_TINT = {100, 100, 100, 255}

-- Each facet is enlarged by this factor around its centre, so that neighbours overlap and
-- no gap opens where the bubble curves. The texture follows each point's real position,
-- so overlapping facets show the same cloth.
local OVERLAP = 1.08

local S = dofile(LockOn_Options.common_script_path.."IFR_CURTAIN/shapes.lua").find(LockOn_Options.script_path)
-- declare.lua only declares the curtain for an aircraft listed in shapes.lua.
assert(S, "IFR curtain: no shape for "..tostring(LockOn_Options.script_path))
for _, wall in ipairs({"left", "right", "up", "down", "front", "back"}) do
	assert(S[wall] and S[wall] > 0, "IFR curtain: wall '"..wall.."' must be above 0")
end
assert(S.squareness and S.squareness > 1, "IFR curtain: squareness must be above 1")
local N = S.squareness
local TEXTURE_METERS = math.max(S.left + S.right, S.up + S.down, S.front + S.back) + 0.2
local STEP = BASE_STEP * math.max(1, TEXTURE_METERS / 3.0)

-- Signed power: keeps the sign of v.
local function spow(v, e)
	if v < 0 then
		return -((-v) ^ e)
	end
	return v ^ e
end

-- Semi-axis on each side of the origin.
local function axes(x, y, z)
	return (x < 0) and S.left or S.right,
	       (y < 0) and S.down or S.up,
	       (z < 0) and S.back or S.front
end

-- Point of the surface seen from the origin in the direction of q: q is moved along the
-- line to the origin until it lies on the bubble. Points of the box (the six walls) cover
-- the whole bubble this way, once each.
local function surface_point(q)
	local a, b, c = axes(q[1], q[2], q[3])
	local f = math.abs(q[1] / a) ^ N + math.abs(q[2] / b) ^ N + math.abs(q[3] / c) ^ N
	local k = f ^ (-1 / N)
	return {q[1] * k, q[2] * k, q[3] * k}
end

-- Outward normal of the surface at point p.
local function surface_normal(p)
	local a, b, c = axes(p[1], p[2], p[3])
	local nx = spow(p[1] / a, N - 1) / a
	local ny = spow(p[2] / b, N - 1) / b
	local nz = spow(p[3] / c, N - 1) / c
	local len = math.sqrt(nx * nx + ny * ny + nz * nz)
	if len < 1e-9 then
		return {0, 0, 1}
	end
	return {nx / len, ny / len, nz / len}
end

local function sub(p, q) return {p[1] - q[1], p[2] - q[2], p[3] - q[3]} end
local function dot(p, q) return p[1] * q[1] + p[2] * q[2] + p[3] * q[3] end

local count = 0

-- Lower corner of the area covered by the texture, a little outside the bubble.
local TEX_MIN = {-S.left - 0.1, -S.down - 0.1, -S.back - 0.1}

-- Texture coordinates of point p, for a facet facing mostly along the given axis
-- (1 = x, 2 = y, 3 = z): p seen from that side of the box.
local function texture_at(p, axis)
	local a, b
	if axis == 1 then
		a, b = 3, 2      -- seen from the side: forward and up
	elseif axis == 2 then
		a, b = 1, 3      -- seen from above: right and forward
	else
		a, b = 1, 2      -- seen from the front: right and up
	end
	return {(p[a] - TEX_MIN[a]) / TEXTURE_METERS, 1 - (p[b] - TEX_MIN[b]) / TEXTURE_METERS}
end

local function add_facet(i, j, corners)
	-- Centre and normal of the facet.
	local centre = {0, 0, 0}
	for _, p in ipairs(corners) do
		for k = 1, 3 do centre[k] = centre[k] + p[k] / 4 end
	end
	local n = surface_normal(centre)

	-- Pitch then yaw that turn the element's normal (+z) onto n:
	-- n = (cos(p) sin(yaw), -sin(p), cos(p) cos(yaw)).
	local pitch = -math.asin(math.max(-1, math.min(1, n[2])))
	local yaw = math.atan2 and math.atan2(n[1], n[3]) or math.atan(n[1], n[3])
	-- The element's own axes once turned, to express the corners in its plane.
	local ex = {math.cos(yaw), 0, -math.sin(yaw)}
	local ey = {math.sin(yaw) * math.sin(pitch), math.cos(pitch), math.cos(yaw) * math.sin(pitch)}

	local vertices = {}
	for k, p in ipairs(corners) do
		local d = sub(p, centre)
		vertices[k] = {dot(d, ex) * OVERLAP, dot(d, ey) * OVERLAP}
	end

	-- Texture from each vertex's real position (after enlarging), seen from the side of the
	-- box the facet faces most.
	local axis = 1
	for k = 2, 3 do
		if math.abs(n[k]) > math.abs(n[axis]) then axis = k end
	end
	local tex_coords = {}
	for k, v in ipairs(vertices) do
		local p = {
			centre[1] + v[1] * ex[1] + v[2] * ey[1],
			centre[2] + v[1] * ex[2] + v[2] * ey[2],
			centre[3] + v[1] * ex[3] + v[2] * ey[3],
		}
		tex_coords[k] = texture_at(p, axis)
	end

	count = count + 1
	local pivot = "ifr_curtain_pivot_"..count
	local p    = CreateElement "ceSimple"
	p.name     = pivot
	p.init_pos = centre
	p.init_rot = {0, YAW_SIGN * math.deg(yaw), 0}
	Add(p)

	local e
	if DEBUG_COLOURS then
		e          = CreateElement "ceMeshPoly"
		e.material = MakeMaterial(nil, DEBUG_FACE_COLOURS[(i + j) % 2 + 1])
	else
		e            = CreateElement "ceTexPoly"
		e.material   = MakeMaterial(CURTAIN_TEXTURE, CURTAIN_TINT)
		e.tex_coords = tex_coords
	end
	e.name           = "ifr_curtain_facet_"..count
	e.primitivetype  = "triangles"
	e.vertices       = vertices
	-- Both windings, so the facet is visible from either side.
	e.indices        = {0, 1, 2, 0, 2, 3, 0, 2, 1, 0, 3, 2}
	e.parent_element = pivot
	e.init_rot       = {0, 0, PITCH_SIGN * math.deg(pitch)}
	e.element_params = {"IFR_CURTAIN"}
	e.controllers    = {{"parameter_in_range", 0, 0.5, 1.5}}
	e.isvisible      = true
	e.use_mipfilter  = true
	Add(e)
end

-- Cut points in [a0, a1]: every STEP (counted from 0) plus the extra points given, in
-- increasing order, without duplicates (which would make facets of zero width).
local function cuts(a0, a1, extra)
	local points = {a0, a1}
	local k = math.floor(a0 / STEP) + 1
	while k * STEP < a1 - 1e-6 do
		points[#points + 1] = k * STEP
		k = k + 1
	end
	for _, p in ipairs(extra or {}) do
		if p > a0 + 1e-6 and p < a1 - 1e-6 then
			points[#points + 1] = p
		end
	end
	table.sort(points)
	local unique = {points[1]}
	for i = 2, #points do
		if points[i] - unique[#unique] > 1e-6 then
			unique[#unique + 1] = points[i]
		end
	end
	return unique
end

-- Covers one part of the box with facets. a and b are distances in meters along the part;
-- box(a, b) gives the point of the box for them, which is then brought onto the bubble.
local function cover(a0, a1, a_extra, b0, b1, box)
	local as = cuts(a0, a1, a_extra)
	local bs = cuts(b0, b1)
	for i = 1, #as - 1 do
		for j = 1, #bs - 1 do
			local aa, ab, ba, bb = as[i], as[i + 1], bs[j], bs[j + 1]
			add_facet(i, j, {
				surface_point(box(aa, bb)),
				surface_point(box(ab, bb)),
				surface_point(box(ab, ba)),
				surface_point(box(aa, ba)),
			})
		end
	end
end

local L, R, U, D, F, B = S.left, S.right, S.up, S.down, S.front, S.back

-- Walls all round, as one band: a runs round the box at the height b, starting at the
-- middle of the back wall and going right.
local corners_round = {R, R + B + F, R + B + F + R + L, R + B + F + R + L + F + B}
local function round_the_walls(a, b)
	if a <= corners_round[1] then
		return {a, b, -B}
	elseif a <= corners_round[2] then
		return {R, b, -B + (a - corners_round[1])}
	elseif a <= corners_round[3] then
		return {R - (a - corners_round[2]), b, F}
	elseif a <= corners_round[4] then
		return {-L, b, F - (a - corners_round[3])}
	end
	return {-L + (a - corners_round[4]), b, -B}
end
cover(0, corners_round[4] + L, corners_round, -D, U, round_the_walls)

-- Ceiling and floor: a runs left to right, b front to back.
cover(-L, R, nil, -B, F, function(a, b) return {a, U, b} end)
cover(-L, R, nil, -B, F, function(a, b) return {a, -D, b} end)
